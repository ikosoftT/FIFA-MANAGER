import { writeFileSync } from "node:fs";
import { createInitialTournament } from "../src/data/initialTournament";

const state = createInitialTournament();
const tournamentId = "13370000-0000-4000-8000-000000000001";
const playerUuid = (index: number) => "13370000-0000-4000-9000-" + String(index + 1).padStart(12, "0");
const matchUuid = (number: number) => "13370000-0000-4000-a000-" + String(number).padStart(12, "0");
const quote = (value: string) => "'" + value.replaceAll("'", "''") + "'";
const playerIds = new Map(state.players.map((player, index) => [player.id, playerUuid(index)]));

const playerValues = state.players.map((player, index) =>
  "(" + quote(playerUuid(index)) + "::uuid," + quote(player.id) + "," + quote(tournamentId) + "::uuid," +
  quote(player.username) + "," + quote(player.username.toLowerCase()) + ",'active')"
).join(",\n  ");

const matchValues = state.matches.map(match => {
  const p1 = match.player1Id ? quote(playerIds.get(match.player1Id)!) + "::uuid" : "null";
  const p2 = match.player2Id ? quote(playerIds.get(match.player2Id)!) + "::uuid" : "null";
  const s1 = match.player1Source ? quote(matchUuid(Number(match.player1Source.matchId.slice(1)))) + "::uuid" : "null";
  const s2 = match.player2Source ? quote(matchUuid(Number(match.player2Source.matchId.slice(1)))) + "::uuid" : "null";
  return "(" + quote(matchUuid(match.number)) + "::uuid," + quote(match.id) + "," + quote(tournamentId) + "::uuid," +
    match.number + "," + match.round + "," + match.roundMatch + "," + p1 + "," + p2 + "," + s1 + "," + s2 + ",'pending')";
}).join(",\n  ");

const sql = [
  "-- Generated by scripts/generate-seed.ts. Safe to execute repeatedly.",
  "begin;",
  "insert into public.tournaments(id,external_key,name,description,status,format,start_date,duration_days,match_duration_minutes,timezone)",
  "values('" + tournamentId + "'::uuid,'1337-fifa-2026','1337 FIFA Tournament','Five days. Fifty-eight contenders. One champion.','upcoming','single_elimination',null,5,10,'Africa/Casablanca')",
  "on conflict (external_key) do nothing;",
  "",
  "insert into public.players(id,external_key,tournament_id,username,normalized_username,status)",
  "values",
  "  " + playerValues,
  "on conflict (tournament_id,external_key) do nothing;",
  "",
  "insert into public.matches(id,external_key,tournament_id,match_number,round_number,round_match_number,player1_id,player2_id,player1_source_match_id,player2_source_match_id,status)",
  "values",
  "  " + matchValues,
  "on conflict (tournament_id,external_key) do nothing;",
  "commit;",
  "",
  "-- After creating the organizer in Authentication > Users, authorize exactly that UUID:",
  "-- insert into private.admin_users(user_id) values ('YOUR-AUTH-USER-UUID') on conflict do nothing;",
  "",
].join("\n");

writeFileSync("supabase/seed.sql", sql);
